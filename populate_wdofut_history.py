def parse_val(v_str: str) -> float:
    # 5.155,00 -> 5155.00
    cleaned = v_str.strip().replace(".", "").replace(",", ".")
    return float(cleaned)

def populate():
    lines = [l.strip() for l in DATA_RAW.strip().split("\n") if l.strip()]
    records = []
    for line in lines:
        parts = line.split("\t")
        if len(parts) < 5:
            continue
        d_str, open_s, high_s, low_s, close_s = parts[0], parts[1], parts[2], parts[3], parts[4]
        d_val = datetime.strptime(d_str, "%d/%m/%Y").date()
        open_p = parse_val(open_s)
        high_p = parse_val(high_s)
        low_p = parse_val(low_s)
        close_p = parse_val(close_s)
        records.append((d_val, "WDOFUT", open_p, high_p, low_p, close_p))

    print(f"Total de registros a inserir: {len(records)}")

    conn = psycopg2.connect(DB_DSN)
    cur = conn.cursor()

    # Deletar dados antigos corrompidos de WDOFUT
    cur.execute("DELETE FROM daily_ohlc WHERE ticker = 'WDOFUT';")

    insert_query = """
        INSERT INTO daily_ohlc (date, ticker, open_p, high_p, low_p, close_p)
        VALUES (%s, %s, %s, %s, %s, %s)
        ON CONFLICT (date, ticker) DO UPDATE 
        SET open_p = EXCLUDED.open_p,
            high_p = EXCLUDED.high_p,
            low_p = EXCLUDED.low_p,
            close_p = EXCLUDED.close_p;
    """
    cur.executemany(insert_query, records)
    conn.commit()
    cur.close()
    conn.close()
    print("✅ Tabela daily_ohlc atualizada com sucesso para WDOFUT!")

if __name__ == "__main__":
    populate()
